import { readFileSync, writeFileSync } from "node:fs";

const readmeContent = readFileSync("readme.md", "utf8");

const featureRegex = /^-\s+(\[N\/A\]|\[x\]|\[ \])\s+\*\*([a-z0-9-]+)\*\*\s+-\s+(.+)$/gm;

const statusMap: Record<string, string> = {
  "[x]": "done",
  "[ ]": "todo",
  "[N/A]": "N/A",
};

const features: { id: string; status: string; description: string }[] = [];
const seen = new Set<string>();

for (const match of readmeContent.matchAll(featureRegex)) {
  const rawStatus = match[1];
  const status = statusMap[rawStatus] ?? rawStatus;
  const id = match[2];
  const description = match[3];
  if (!seen.has(id)) {
    seen.add(id);
    features.push({ id, status, description });
  }
}

features.sort((a, b) => a.id.localeCompare(b.id));

const output = `// Auto-generated by build/readme-parser.ts
// Do not edit manually

export const featuresMeta = ${JSON.stringify(features, null, "\t")} as const;

export type FeatureStatus = "done" | "todo" | "N/A";

export interface FeatureMeta {
\tid: string;
\tstatus: FeatureStatus;
\tdescription: string;
}
`;

writeFileSync("source/feature-data.ts", output);
console.log(`Generated ${features.length} features`);
